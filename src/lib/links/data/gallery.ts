// Helper functions
export function getGalleryItemsByCategory(categoryId: string): GalleryItem[] {
    if (categoryId === 'all') return galleryItems;
    return galleryItems.filter(item => item.category === categoryId);
}

export function getGalleryItemsByTag(tag: string): GalleryItem[] {
    return galleryItems.filter(item =>
        item.tags.some(itemTag => itemTag.toLowerCase().includes(tag.toLowerCase()))
    );
}

export function getFeaturedGalleryItems(): GalleryItem[] {
    return galleryItems.filter(item => item.featured);
}

export function getAllTags(): string[] {
    const tags = new Set<string>();
    galleryItems.forEach(item => {
        item.tags.forEach(tag => tags.add(tag));
    });
    return Array.from(tags).sort();
}
